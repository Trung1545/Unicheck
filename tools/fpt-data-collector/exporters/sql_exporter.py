from pathlib import Path
from models import MasterDataset

class SqlSeedExporter:
    @staticmethod
    def escape(s: str) -> str:
        if s is None:
            return "NULL"
        return "'" + str(s).replace("'", "''") + "'"

    @classmethod
    def export(cls, dataset: MasterDataset, output_path: str):
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)

        lines = []
        lines.append("-- ==============================================================================")
        lines.append("-- UniCheck - FPT University Master Seed Data (Validated Synthetic Dataset)")
        lines.append("-- Generated by tools/fpt-data-collector")
        lines.append("-- All testing users use test domain: @test.unicheck.edu.vn")
        lines.append("-- Idempotent: ON CONFLICT DO NOTHING")
        lines.append("-- ==============================================================================")
        lines.append("")
        lines.append("BEGIN;")
        lines.append("")

        # 1. Majors
        lines.append("-- 1. MAJORS")
        for m in dataset.majors:
            lines.append(
                f"INSERT INTO majors (code, name, description, program_duration, status) "
                f"VALUES ({cls.escape(m.code)}, {cls.escape(m.name)}, {cls.escape(m.description)}, {cls.escape(m.program_duration)}, {cls.escape(m.status)}) "
                f"ON CONFLICT (code) DO NOTHING;"
            )
        lines.append("")

        # 2. Specializations
        lines.append("-- 2. SPECIALIZATIONS")
        for s in dataset.specializations:
            lines.append(
                f"INSERT INTO specializations (code, name, description, major_id, status) "
                f"VALUES ({cls.escape(s.code)}, {cls.escape(s.name)}, {cls.escape(s.description)}, (SELECT id FROM majors WHERE code = {cls.escape(s.major_code)}), {cls.escape(s.status)}) "
                f"ON CONFLICT (code) DO NOTHING;"
            )
        lines.append("")

        # 3. Courses
        lines.append("-- 3. COURSES")
        for c in dataset.courses:
            lines.append(
                f"INSERT INTO courses (code, name, description, credits, number_of_slots, status, is_calculated_in_gpa) "
                f"VALUES ({cls.escape(c.code)}, {cls.escape(c.name)}, {cls.escape(c.description)}, {c.credits}, {c.number_of_slots}, {cls.escape(c.status)}, {'TRUE' if c.is_calculated_in_gpa else 'FALSE'}) "
                f"ON CONFLICT (code) DO NOTHING;"
            )
        lines.append("")

        # 4. Course Prerequisites
        lines.append("-- 4. COURSE PREREQUISITES")
        for p in dataset.course_prerequisites:
            lines.append(
                f"INSERT INTO course_prerequisites (course_id, prerequisite_id) "
                f"VALUES ((SELECT id FROM courses WHERE code = {cls.escape(p.course_code)}), (SELECT id FROM courses WHERE code = {cls.escape(p.prerequisite_code)})) "
                f"ON CONFLICT (course_id, prerequisite_id) DO NOTHING;"
            )
        lines.append("")

        # 5. Semesters & Slot Types
        lines.append("-- 5. SEMESTERS & SLOT TYPES")
        for sem in dataset.semesters:
            lines.append(
                f"INSERT INTO semesters (code, name, start_date, end_date, status, description) "
                f"VALUES ({cls.escape(sem.code)}, {cls.escape(sem.name)}, {cls.escape(sem.start_date)}, {cls.escape(sem.end_date)}, {cls.escape(sem.status)}, {cls.escape(sem.description)}) "
                f"ON CONFLICT (code) DO NOTHING;"
            )
        lines.append("")

        # Slot types attached to FALL2026
        lines.append("-- 5.1 SLOT TYPES")
        for st in dataset.slot_types:
            lines.append(
                f"INSERT INTO slot_types (name, slot_index, start_time, end_time, duration, semester_id, description) "
                f"SELECT {cls.escape(st.name)}, {st.slot_index}, {cls.escape(st.start_time)}::TIME, {cls.escape(st.end_time)}::TIME, {cls.escape(st.duration)}, s.id, {cls.escape(st.description)} "
                f"FROM semesters s WHERE s.code = 'FALL2026' "
                f"AND NOT EXISTS (SELECT 1 FROM slot_types WHERE semester_id = s.id AND slot_index = {st.slot_index});"
            )
        lines.append("")

        # 6. Rooms & WiFi Access Points
        lines.append("-- 6. ROOMS & WIFI ACCESS POINTS")
        for r in dataset.rooms:
            lines.append(
                f"INSERT INTO rooms (code, name, capacity, building, floor, type, status) "
                f"VALUES ({cls.escape(r.code)}, {cls.escape(r.name)}, {r.capacity}, {cls.escape(r.building)}, {r.floor}, {cls.escape(r.type)}, {cls.escape(r.status)}) "
                f"ON CONFLICT (code) DO NOTHING;"
            )
        lines.append("")

        for ap in dataset.wifi_aps:
            lines.append(
                f"INSERT INTO wifi_access_points (ssid, bssid, name, location, status) "
                f"VALUES ({cls.escape(ap.ssid)}, {cls.escape(ap.bssid)}, {cls.escape(ap.name)}, {cls.escape(ap.location)}, {cls.escape(ap.status)}) "
                f"ON CONFLICT (bssid) DO NOTHING;"
            )
            if ap.room_code:
                lines.append(
                    f"INSERT INTO room_wifi_access_points (room_id, wifi_access_point_id, signal_strength, is_primary) "
                    f"SELECT r.id, w.id, -55, TRUE FROM rooms r, wifi_access_points w "
                    f"WHERE r.code = {cls.escape(ap.room_code)} AND w.bssid = {cls.escape(ap.bssid)} "
                    f"ON CONFLICT (room_id, wifi_access_point_id) DO NOTHING;"
                )
        lines.append("")

        # 7. Users & Profiles
        lines.append("-- 7. USERS (ADMIN, LECTURERS, STUDENTS)")
        for u in dataset.users:
            lines.append(
                f"INSERT INTO users (code, username, password, full_name, email, dob, phone, sex, role, status, face_data_status) "
                f"VALUES ({cls.escape(u.code)}, {cls.escape(u.username)}, {cls.escape(u.password_hash)}, {cls.escape(u.full_name)}, {cls.escape(u.email)}, "
                f"{cls.escape(u.dob)}::DATE, {cls.escape(u.phone)}, {cls.escape(u.sex)}, {cls.escape(u.role)}, {cls.escape(u.status)}, {cls.escape(u.face_data_status)}) "
                f"ON CONFLICT (username) DO NOTHING;"
            )
        lines.append("")

        lines.append("-- 7.1 LECTURER PROFILES")
        for lp in dataset.lecturer_profiles:
            lines.append(
                f"INSERT INTO lecturer_profiles (user_id, department, expertise, bio) "
                f"SELECT u.id, {cls.escape(lp.department)}, {cls.escape(lp.expertise)}, {cls.escape(lp.bio)} "
                f"FROM users u WHERE u.username = {cls.escape(lp.username)} "
                f"ON CONFLICT (user_id) DO NOTHING;"
            )
        lines.append("")

        lines.append("-- 7.2 STUDENT PROFILES")
        for sp in dataset.student_profiles:
            lines.append(
                f"INSERT INTO student_profiles (user_id, course, gpa, major_id, specialization_id) "
                f"SELECT u.id, {cls.escape(sp.course)}, {sp.gpa}, "
                f"(SELECT id FROM majors WHERE code = {cls.escape(sp.major_code)}), "
                f"(SELECT id FROM specializations WHERE code = {cls.escape(sp.specialization_code)}) "
                f"FROM users u WHERE u.username = {cls.escape(sp.username)} "
                f"ON CONFLICT (user_id) DO NOTHING;"
            )
        lines.append("")

        # 8. Class Sections & Enrollments
        lines.append("-- 8. CLASS SECTIONS")
        for cls_rec in dataset.class_sections:
            lines.append(
                f"INSERT INTO class_sections (class_name, course_id, semester_id, lecturer_id, number_of_slots, max_students, current_enrollment, status) "
                f"SELECT {cls.escape(cls_rec.class_name)}, "
                f"(SELECT id FROM courses WHERE code = {cls.escape(cls_rec.course_code)}), "
                f"(SELECT id FROM semesters WHERE code = {cls.escape(cls_rec.semester_code)}), "
                f"(SELECT id FROM users WHERE username = {cls.escape(cls_rec.lecturer_username)}), "
                f"{cls_rec.number_of_slots}, {cls_rec.max_students}, {cls_rec.current_enrollment}, {cls.escape(cls_rec.status)} "
                f"ON CONFLICT (class_name) DO NOTHING;"
            )
        lines.append("")

        lines.append("-- 8.1 ENROLLMENTS")
        for enr in dataset.enrollments:
            lines.append(
                f"INSERT INTO enrollments (class_name, student_code, student_id, status) "
                f"SELECT {cls.escape(enr.class_name)}, {cls.escape(enr.student_code)}, u.id, {cls.escape(enr.status)} "
                f"FROM users u WHERE u.username = {cls.escape(enr.student_username)} "
                f"ON CONFLICT (class_name, student_id) DO NOTHING;"
            )
        lines.append("")

        # 9. Timetable Slots
        lines.append("-- 9. TIMETABLE SLOTS")
        for slot in dataset.timetable_slots:
            lines.append(
                f"INSERT INTO timetable_slots (class_name, room_id, slot_type_id, date, day_of_week, slot_number, status, note) "
                f"SELECT {cls.escape(slot.class_name)}, "
                f"(SELECT id FROM rooms WHERE code = {cls.escape(slot.room_code)}), "
                f"(SELECT id FROM slot_types WHERE slot_index = {slot.slot_number} LIMIT 1), "
                f"{cls.escape(slot.date)}::DATE, {slot.day_of_week}, {slot.slot_number}, {cls.escape(slot.status)}, {cls.escape(slot.note)} "
                f"WHERE NOT EXISTS (SELECT 1 FROM timetable_slots WHERE class_name = {cls.escape(slot.class_name)} AND date = {cls.escape(slot.date)}::DATE AND slot_number = {slot.slot_number});"
            )
        lines.append("")

        # 10. Attendance Sessions
        lines.append("-- 10. ATTENDANCE SESSIONS")
        for sess in dataset.attendance_sessions:
            c_name, d_str, slot_part = sess.slot_key.split("_")
            s_num = int(slot_part.replace("SLOT", ""))
            lines.append(
                f"INSERT INTO attendance_sessions (timetable_slot_id, lecturer_id, opened_at, closed_at, status) "
                f"SELECT t.id, (SELECT id FROM users WHERE username = {cls.escape(sess.lecturer_username)}), "
                f"{cls.escape(sess.opened_at)}::TIMESTAMP, {cls.escape(sess.closed_at)}::TIMESTAMP, {cls.escape(sess.status)} "
                f"FROM timetable_slots t WHERE t.class_name = {cls.escape(c_name)} AND t.date = {cls.escape(d_str)}::DATE AND t.slot_number = {s_num} "
                f"ON CONFLICT (timetable_slot_id) DO NOTHING;"
            )
        lines.append("")

        # 11. Student Attendances
        lines.append("-- 11. STUDENT ATTENDANCES")
        for att in dataset.student_attendances:
            c_name, d_str, slot_part = att.slot_key.split("_")
            s_num = int(slot_part.replace("SLOT", ""))
            lines.append(
                f"INSERT INTO student_attendances (session_id, student_id, status, method, check_in_time, face_confidence, wifi_bssid, wifi_rssi) "
                f"SELECT s.id, u.id, {cls.escape(att.status)}, {cls.escape(att.method)}, {cls.escape(att.check_in_time)}::TIMESTAMP, "
                f"{att.face_confidence if att.face_confidence is not None else 'NULL'}, {cls.escape(att.wifi_bssid)}, {att.wifi_rssi if att.wifi_rssi is not None else 'NULL'} "
                f"FROM attendance_sessions s "
                f"JOIN timetable_slots t ON s.timetable_slot_id = t.id "
                f"JOIN users u ON u.username = {cls.escape(att.student_username)} "
                f"WHERE t.class_name = {cls.escape(c_name)} AND t.date = {cls.escape(d_str)}::DATE AND t.slot_number = {s_num} "
                f"AND NOT EXISTS (SELECT 1 FROM student_attendances sa WHERE sa.session_id = s.id AND sa.student_id = u.id);"
            )
        lines.append("")

        # 12. Sequence updates
        lines.append("-- 12. SEQUENCE RESET FOR POSTGRESQL")
        sequences = [
            "majors_id_seq",
            "specializations_id_seq",
            "courses_id_seq",
            "semesters_id_seq",
            "slot_types_id_seq",
            "rooms_id_seq",
            "wifi_access_points_id_seq",
            "room_wifi_access_points_id_seq",
            "users_id_seq",
            "enrollments_id_seq",
            "timetable_slots_id_seq",
            "attendance_sessions_id_seq",
            "student_attendances_id_seq",
        ]
        for seq in sequences:
            tbl = seq.replace("_id_seq", "")
            lines.append(f"SELECT setval('{seq}', COALESCE((SELECT MAX(id) FROM {tbl}), 1));")

        lines.append("")
        lines.append("COMMIT;")
        lines.append("")

        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

        print(f"[EXPORTER] SQL Seed script exported: {path} ({len(lines)} lines, {path.stat().st_size} bytes)")
